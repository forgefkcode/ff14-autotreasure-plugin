"""用法：python treasure_items.py <放 Garland JSON 的資料夾> [輸出的 TreasureOnlyItems.cs]
從 Garland Tools 的地圖、寶物庫資料挑出「只有挖寶拿得到」的物品：來源只有 treasure（地圖寶箱）或寶物庫副本。
資料夾裡要有 地圖ID.json、in寶物庫ID.json、it物品ID.json（物品 https://www.garlandtools.org/db/doc/item/en/3/ID.json，
副本 https://www.garlandtools.org/db/doc/instance/en/2/ID.json）。--fetch：先把缺的檔案下載到資料夾"""
import json, os, sys, time, urllib.request
sys.stdout.reconfigure(encoding="utf-8")
FETCH = "--fetch" in sys.argv
sys.argv = [a for a in sys.argv if a != "--fetch"]
DIR = sys.argv[1]
OTHER = {'drops', 'nodes', 'tradeShops', 'quests', 'ventures', 'reducedFrom', 'voyages', 'craft', 'leves', 'desynthedFrom',
         'vendors', 'fishingSpots', 'bingoReward', 'achievements', 'requiredByLeves', 'supply', 'satisfaction', 'coffers'}
# 7.3: G18 (Gargantuaskin) and its vault Vault Oneiron; on TC 7.3 the Vault Oneiron rewards also come out of the G17 vault
MAPS = {26745: "G12", 36612: "G14", 39591: "G15", 43557: "G17", 46185: "G18"}
INST = {55006: "G12", 55008: "G12", 55009: "G14", 55011: "G15", 55012: "G17", 55013: "G18"}


def load(name):
    path = os.path.join(DIR, name)
    if FETCH and not os.path.exists(path):
        kind, num = ("instance", name[2:-5]) if name.startswith("in") else ("item", name.removeprefix("it")[:-5])
        url = f"https://www.garlandtools.org/db/doc/{kind}/en/{2 if kind == 'instance' else 3}/{num}.json"
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})  # the default urllib agent gets 403
        with urllib.request.urlopen(req) as r, open(path, "wb") as f:
            f.write(r.read())
        time.sleep(0.2)
    return json.load(open(path, encoding="utf-8"))


where = {}
for m, g in MAPS.items():
    for i in load(f"{m}.json")['item']['loot']:
        where.setdefault(i, set()).add(g)
for v, g in INST.items():
    for i in load(f"in{v}.json")['instance'].get('rewards', []):
        where.setdefault(i, set()).add(g)
keep, drop = [], []
for i in sorted(where):
    d = load(f"it{i}.json")
    it = d['item']
    # 寶物庫：Garland 分類是 Treasure Hunt 的副本（含 7.x 的 Vault Oneiron）
    insts = {x['obj'].get('t') for x in d.get('partials', []) if x['type'] == 'instance'}
    other = (OTHER & set(it)) | ({'instance'} if insts - {'Treasure Hunt'} else set())
    row = (i, it['name'], ",".join(sorted(where[i])), sorted(other))
    (drop if other else keep).append(row)
for r in keep:
    print("KEEP", *r[:3])
for r in drop:
    print("drop", *r)
if len(sys.argv) > 2:
    nl = chr(10)
    body = nl.join(f"        {i}, // {n} ({g})" for i, n, g, _ in keep)
    text = (f"namespace AutoTreasure;{nl}{nl}"
            f"// Generated by tools/treasure_items.py from Garland Tools: items whose only sources are treasure map coffers or{nl}"
            f"// treasure hunt vaults (G12 / G14 / G15 / G17 / G18 map loot and vault rewards). The loot list shows these by default.{nl}"
            f"public static class TreasureOnlyItems{nl}{{{nl}    public static readonly HashSet<uint> Ids ={nl}    [{nl}"
            f"{body}{nl}    ];{nl}}}{nl}")
    open(sys.argv[2], "w", encoding="utf-8", newline="").write(text)
